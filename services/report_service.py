"""PDF Report Generation Service for ClauseLens.
Generates an audit-ready, tamper-evident PDF summary of policy findings using ReportLab.
Escapes all dynamic text, handles multi-page pagination, and includes strict legal disclaimers.
"""
import io
import json
import xml.sax.saxutils as saxutils
from datetime import datetime
from typing import Dict, Any, List

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, PageBreak, HRFlowable
)
from reportlab.pdfgen import canvas

DISCLAIMER_TEXT = (
    "ClauseLens provides policy-based assistance and is not legal advice. It checks only the supported "
    "clause types against the policies you configured. The absence of a flagged issue does not mean a contract "
    "is safe or complete. Consult a qualified professional before signing."
)


class NumberedCanvas(canvas.Canvas):
    """Canvas that computes total pages dynamically and stamps header/footer on every page."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#555555"))

        # Running header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(54, 11 * 72 - 36, "ClauseLens — Policy Verification Report")
            self.setStrokeColor(colors.HexColor("#D0D7DE"))
            self.setLineWidth(0.5)
            self.line(54, 11 * 72 - 42, 8.5 * 72 - 54, 11 * 72 - 42)

        # Running footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * 72 - 54, 36, footer_text)
        self.drawString(54, 36, "Confidential — Generated by ClauseLens (Local Assistance Only)")
        self.setStrokeColor(colors.HexColor("#D0D7DE"))
        self.setLineWidth(0.5)
        self.line(54, 48, 8.5 * 72 - 54, 48)
        self.restoreState()


def escape_text(text: Any) -> str:
    """Escape text for ReportLab XML/HTML Paragraph parsing."""
    if text is None:
        return ""
    val = str(text)
    return saxutils.escape(val)


def generate_pdf_report(
    analysis: Dict[str, Any],
    findings: List[Dict[str, Any]],
    policies: List[Dict[str, Any]]
) -> bytes:
    """Generate a high-quality PDF report from stored analysis and findings data.
    Returns bytes of the generated PDF.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()

    # Custom styles
    primary_color = colors.HexColor("#0B1F3A")
    text_color = colors.HexColor("#1A202C")
    muted_color = colors.HexColor("#4A5568")

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=primary_color,
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=muted_color,
        spaceAfter=14
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=primary_color,
        spaceBefore=12,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=text_color
    )

    body_bold = ParagraphStyle(
        "ReportBodyBold",
        parent=body_style,
        fontName="Helvetica-Bold"
    )

    quote_style = ParagraphStyle(
        "ReportQuote",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#2D3748"),
        leftIndent=10,
        rightIndent=10
    )

    disclaimer_style = ParagraphStyle(
        "DisclaimerStyle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#4A5568")
    )

    story = []

    # Title & Metadata
    filename_clean = escape_text(analysis.get("filename", "Contract"))
    analysis_date = escape_text(analysis.get("created_at", datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")))
    file_type = escape_text(str(analysis.get("file_type", "pdf")).upper())
    length_desc = f"{analysis.get('page_count_or_paragraph_count', 0)} {'Pages' if analysis.get('file_type') == 'pdf' else 'Paragraphs'}"
    nemotron_used = bool(analysis.get("nemotron_used", 0))

    story.append(Paragraph("ClauseLens Policy Review Report", title_style))
    story.append(Paragraph(f"Analysis for: <b>{filename_clean}</b> &nbsp;|&nbsp; Generated: {analysis_date}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceAfter=10))

    # Document Overview Table
    doc_meta_data = [
        [
            Paragraph("<b>File Format:</b>", body_style),
            Paragraph(file_type, body_style),
            Paragraph("<b>Length:</b>", body_style),
            Paragraph(escape_text(length_desc), body_style)
        ],
        [
            Paragraph("<b>Extraction Status:</b>", body_style),
            Paragraph(escape_text(analysis.get("extraction_status", "success")), body_style),
            Paragraph("<b>Advanced AI Used:</b>", body_style),
            Paragraph("Yes (Nemotron)" if nemotron_used else "No (Rule-based only)", body_style)
        ]
    ]

    domain_val = analysis.get("domain")
    doc_type_val = analysis.get("document_type")
    if domain_val or doc_type_val:
        doc_meta_data.append([
            Paragraph("<b>Domain:</b>", body_style),
            Paragraph(escape_text(str(domain_val or "Not Specified")), body_style),
            Paragraph("<b>Document Profile:</b>", body_style),
            Paragraph(escape_text(str(doc_type_val or "General")), body_style)
        ])

    jurisdiction_val = analysis.get("jurisdiction")
    issuing_auth_val = analysis.get("issuing_authority")
    if jurisdiction_val or issuing_auth_val:
        doc_meta_data.append([
            Paragraph("<b>Jurisdiction:</b>", body_style),
            Paragraph(escape_text(str(jurisdiction_val or "India")), body_style),
            Paragraph("<b>Issuing Authority:</b>", body_style),
            Paragraph(escape_text(str(issuing_auth_val or "Not Specified")), body_style)
        ])

    t_meta = Table(doc_meta_data, colWidths=[110, 140, 110, 140])
    t_meta.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
    ]))
    story.append(t_meta)
    story.append(Spacer(1, 10))

    # Summary Statistics
    conflicts_count = sum(1 for f in findings if f.get("status") == "potential_conflict")
    reviews_count = sum(1 for f in findings if f.get("status") == "review_recommended")
    no_conflicts_count = sum(1 for f in findings if f.get("status") == "no_conflict_detected")

    summary_table_data = [
        [
            Paragraph("<b>Potential Policy Conflicts</b>", body_bold),
            Paragraph("<b>Review Recommended</b>", body_bold),
            Paragraph("<b>No Conflict Detected</b>", body_bold)
        ],
        [
            Paragraph(f"<font color='#D32F2F' size='14'><b>{conflicts_count}</b></font>", body_style),
            Paragraph(f"<font color='#B26A00' size='14'><b>{reviews_count}</b></font>", body_style),
            Paragraph(f"<font color='#2E7D32' size='14'><b>{no_conflicts_count}</b></font>", body_style)
        ]
    ]
    t_summary = Table(summary_table_data, colWidths=[166, 166, 168])
    t_summary.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#E2E8F0")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(t_summary)
    story.append(Spacer(1, 12))

    # Disclaimer Callout Box
    disclaimer_box = [
        [Paragraph(f"<b>Important Legal Notice:</b><br/>{escape_text(DISCLAIMER_TEXT)}", disclaimer_style)]
    ]
    t_disc = Table(disclaimer_box, colWidths=[500])
    t_disc.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FFFBEB")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#FDE68A")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(t_disc)
    story.append(Spacer(1, 14))

    # Active Policies Evaluated
    story.append(Paragraph("Active Policies Evaluated", section_heading))
    if isinstance(policies, dict) and "policies" in policies:
        policies = policies["policies"]

    if policies:
        p_data = [["Policy Name", "Type", "Source", "Standard / Parameter"]]
        for p in policies:
            p_name = escape_text(p.get("name", "Unnamed"))
            p_type = escape_text(p.get("type", "").capitalize())
            p_source = "Default Profile" if p.get("source") == "domain_default" else "User Policy"
            raw_p = p.get("params_json") if p.get("params_json") is not None else p.get("params", {})
            p_params = json.loads(raw_p) if isinstance(raw_p, str) else raw_p
            p_desc = escape_text(json.dumps(p_params)) if p_params else escape_text(p.get("explanation", ""))
            p_data.append([
                Paragraph(f"<b>{p_name}</b>", body_style),
                Paragraph(p_type, body_style),
                Paragraph(p_source, body_style),
                Paragraph(p_desc, body_style)
            ])
        t_pol = Table(p_data, colWidths=[140, 70, 80, 210])
        t_pol.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
            ("LINEBELOW", (0, 0), (-1, 0), 1, colors.HexColor("#CBD5E1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(t_pol)
    else:
        story.append(Paragraph("<i>No policies were selected for this run.</i>", body_style))

    story.append(Spacer(1, 16))

    # Findings Section
    story.append(Paragraph("Detailed Findings & Evidence", section_heading))

    if not findings:
        story.append(Paragraph("<b>No conflicts were detected among the supported checks.</b>", body_style))
    else:
        # Sort findings: potential_conflict first, then review_recommended, then no_conflict_detected
        status_order = {"potential_conflict": 0, "review_recommended": 1, "no_conflict_detected": 2}
        sorted_findings = sorted(findings, key=lambda x: status_order.get(x.get("status"), 3))

        for idx, f in enumerate(sorted_findings, start=1):
            status = f.get("status", "review_recommended")
            cat = escape_text(f.get("category", "").upper())
            title = escape_text(f.get("title", "Finding"))
            loc = escape_text(f.get("location_label", "Document-wide"))
            exp = escape_text(f.get("explanation", ""))
            next_step = escape_text(f.get("next_step", ""))
            quote = escape_text(f.get("quote", "").strip())
            manual_rev = bool(f.get("manual_review", 0))

            # Status styling
            if status == "potential_conflict":
                status_label = "POTENTIAL POLICY CONFLICT"
                bg_color = colors.HexColor("#FEF2F2")
                border_color = colors.HexColor("#FCA5A5")
                badge_color = "#D32F2F"
            elif status == "review_recommended":
                status_label = "REVIEW RECOMMENDED"
                bg_color = colors.HexColor("#FFFBEB")
                border_color = colors.HexColor("#FDE68A")
                badge_color = "#B26A00"
            else:
                status_label = "NO CONFLICT DETECTED FOR THIS RULE"
                bg_color = colors.HexColor("#F0FDF4")
                border_color = colors.HexColor("#86EFAC")
                badge_color = "#2E7D32"

            finding_header = (
                f"<b>#{idx}. {title}</b><br/>"
                f"<font color='{badge_color}'><b>[{status_label}]</b></font> &nbsp;|&nbsp; "
                f"<font color='#4A5568'>Category: {cat} &nbsp;|&nbsp; Location: {loc}</font>"
            )

            card_content = [
                [Paragraph(finding_header, body_style)],
                [Paragraph(f"<b>Explanation:</b> {exp}", body_style)],
                [Paragraph(f"<b>Suggested Next Step:</b> {next_step}", body_style)]
            ]

            if quote and quote != "No matching clause detected in document.":
                # Form quote box
                quote_box = (
                    f"<font color='#4A5568'><b>Verified Contract Quote ({loc}):</b></font><br/>"
                    f"\"{quote}\""
                )
                card_content.append([Paragraph(quote_box, quote_style)])

            if manual_rev:
                card_content.append([
                    Paragraph("<font color='#B26A00'><i>* Requires human interpretation by reviewer.</i></font>", body_style)
                ])

            t_card = Table(card_content, colWidths=[500])
            t_card.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), bg_color),
                ("BOX", (0, 0), (-1, -1), 1, border_color),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]))

            story.append(KeepTogether([t_card, Spacer(1, 8)]))

    # Build PDF with dynamic NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
